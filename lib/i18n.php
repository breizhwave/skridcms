function t(string $key, ...$args): string
{
    $s = SK_TEXTS[skrid_lang()][$key] ?? SK_TEXTS['en'][$key] ?? $key;
    return $args ? sprintf($s, ...$args) : $s;
}

/** Texts whose key starts with $prefix, for the browser. */
function t_group(string $prefix): array
{
    $out = [];
    foreach (SK_TEXTS[skrid_lang()] as $k => $v) {
        if (str_starts_with($k, $prefix)) {
            $out[substr($k, strlen($prefix))] = $v;
        }
    }
    return $out;
}
